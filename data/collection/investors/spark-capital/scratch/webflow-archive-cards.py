#!/usr/bin/env python3
"""Read the archived Webflow /companies listings (sources/wayback/raw/<year>-companies.html,
2020+) card by card: name, description, acquisition-spec exit marker, website link, and
the years each company was listed. Writes sources/site/webflow-archive-companies.json, a
file_list source for site-portfolio.py (decisions.md D9: the exit marker is status
corroboration, never a label). Re-run after wayback-pull.py adds a year."""
import json, re, html as H, sys
from pathlib import Path
from collections import OrderedDict
ROOT = Path(__file__).resolve().parents[5]
sys.path.insert(0, str(ROOT / "scripts"))
from paths import Paths, write_atomic
P = Paths("spark-capital")
rows = OrderedDict()
years_read = []
for f in sorted((P.wayback / "raw").glob("*-companies.html")):
    year = int(f.name[:4])
    src = f.read_text(encoding="utf-8", errors="replace")
    if "w-dyn-item" not in src:
        continue
    years_read.append(year)
    ts = json.loads((P.wayback / "raw" / "companies.snapshots.json").read_text()).get(str(year), ["", ""])[0]
    for c in re.split(r'<div[^>]*role="listitem" class="[^"]*w-dyn-item[^"]*">', src)[1:]:
        m = re.search(r'<h3 class="h3 margin-top---0">(.*?)</h3>', c)
        if not m:
            continue
        name = H.unescape(m.group(1)).strip()
        desc = re.search(r'<div class="company-specs[^"]*">(.*?)</div>', c, flags=re.S)
        acq = re.search(r'<div class="acquisition-spec[^"]*">(.*?)</div>', c, flags=re.S)
        links = [l for l in re.findall(r'<a[^>]+href="(https?://[^"]+)"', c)
                 if "website-files" not in l and "sparkcapital.com" not in l and "web.archive.org" not in l]
        r = rows.setdefault(name, {"name": name, "url": "", "description": None, "acquisition_spec": None,
                                   "years_listed": [], "first_snapshot": ts})
        if year not in r["years_listed"]:
            r["years_listed"].append(year)
        if desc and not r["description"]:
            r["description"] = H.unescape(re.sub("<[^>]+>", "", desc.group(1))).strip() or None
        a = H.unescape(acq.group(1)).strip() if acq else ""
        if a:
            r["acquisition_spec"] = a          # latest year wins (markers only accrue)
        if links and not r["url"]:
            r["url"] = links[0]
out = {"_readme": f"Archived sparkcapital.com/companies (Webflow, 2020+) read card by card from the "
       f"wayback-pull raw snapshots for {years_read}; one row per distinct card name with the years it "
       f"was listed, the latest exit marker ('NYSE: TWTR in 2013', 'Acquired by Facebook in 2014') and the "
       f"card's website link. Generated by scratch/webflow-archive-cards.py on the Wayback captures named in "
       f"raw/companies.snapshots.json. Membership evidence: a listing on the firm's own site, any era.",
       "rows": list(rows.values())}
write_atomic(P.site / "webflow-archive-companies.json", json.dumps(out, indent=1) + "\n")
n_exit = sum(1 for r in rows.values() if r["acquisition_spec"])
print(f"years {years_read}: {len(rows)} distinct companies, {n_exit} with an exit marker")
from collections import Counter
print(Counter(len(r["years_listed"]) for r in rows.values()))
print("dropped from the live list (listed 2021-2025, not 2026):",
      sorted(r["name"] for r in rows.values() if 2026 not in r["years_listed"])[:200])
