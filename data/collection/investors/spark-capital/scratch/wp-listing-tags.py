#!/usr/bin/env python3
"""Read the firm's own per-card labels off the archived listing pages (decisions.md D9):
the 2015-2019 WordPress /companies/ cards ('portfolio-list <sector...> <geo> <stage,...>'
with an <a class=portfolio-logos href=/companies/<slug>/ title=Name>) and the 2020 B12
cards ('items-grid__item tag-all tag-sector-<x> tag-stage-<y>' data-title=<name>). Writes
sources/site/wp-companies-2015-2020.json, a file_list source: one row per company with the
site's sector, geography and stage labels per year. The stage label is scored on the gate
before it may corroborate entry_stage; it is never a label on its own."""
import json, re, html as H, sys
from pathlib import Path
from collections import OrderedDict
ROOT = Path(__file__).resolve().parents[5]
sys.path.insert(0, str(ROOT / "scripts"))
from paths import Paths, write_atomic
P = Paths("spark-capital")
GEO = {"california", "new-york", "massachusetts", "international", "other-us"}
STAGE = {"seed", "venture", "growth", "alumni"}
rows = OrderedDict()
years = []
for f in sorted((P.wayback / "raw").glob("*-companies.html")):
    year = int(f.name[:4]); src = f.read_text(encoding="utf-8", errors="replace")
    if "portfolio-list" in src:                      # WordPress 2015-2019
        years.append(year)
        for cls, slug, name in re.findall(
                r'<div class="portfolio-list ([^"]*)"\s*data-id="\d+"\s*>\s*<a class="portfolio-logos" href="[^"]*/companies/([a-z0-9-]+)/" title="([^"]*)"', src):
            toks = [t for t in re.split(r"[\s,]+", cls.strip()) if t]
            r = rows.setdefault(slug, {"slug": slug, "name": H.unescape(name).strip(), "url": "", "labels": {}})
            r["labels"][str(year)] = {"sector": [t for t in toks if t not in GEO | STAGE],
                                       "geo": [t for t in toks if t in GEO], "stage": [t for t in toks if t in STAGE]}
    elif 'class="companies-list' in src:             # WordPress redesign 2018-2019
        years.append(year)
        for cls, href, name in re.findall(
                r'<li class="companies-list ([^"]*)"[^>]*>\s*<a class="portfolio-logos" href="([^"]*)" title="([^"]+)"', src):
            toks = [t for t in cls.split() if t and not t.isdigit()]
            slug = re.sub(r"[^a-z0-9]+", "-", H.unescape(name).lower()).strip("-")
            r = rows.setdefault(slug, {"slug": slug, "name": H.unescape(name).strip(), "url": "", "labels": {}})
            r["url"] = r["url"] or (href if "web.archive.org" not in href and "sparkcapital" not in href else "")
            r["labels"][str(year)] = {"sector": [t for t in toks if t not in GEO | STAGE],
                                       "geo": [], "stage": [t for t in toks if t in STAGE]}
    elif "items-grid__item tag-all" in src:          # B12 2020
        years.append(year)
        for cls, title, href in re.findall(
                r'<li class="items-grid__item tag-all([^"]*)" data-title="([^"]*)">.*?<a class="items-grid__item-image" href="([^"]*)"', src, flags=re.S):
            toks = cls.split()
            slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
            r = rows.setdefault(slug, {"slug": slug, "name": title, "url": "", "labels": {}})
            r["url"] = r["url"] or (href if "web.archive.org" not in href and "sparkcapital" not in href else "")
            r["labels"][str(year)] = {"sector": [t.replace("tag-sector-", "") for t in toks if t.startswith("tag-sector-")],
                                       "geo": [], "stage": [t.replace("tag-stage-", "") for t in toks if t.startswith("tag-stage-")]}
for r in rows.values():
    st = [s for y in sorted(r["labels"]) for s in r["labels"][y]["stage"]]
    r["stage_site_first"] = next((s for s in st if s != "alumni"), None)      # earliest non-alumni stage label
    r["stage_site_all"] = sorted(set(st))
    r["sectors_site"] = sorted({s for y in r["labels"] for s in r["labels"][y]["sector"]})
    r["geo_site"] = sorted({g for y in r["labels"] for g in r["labels"][y]["geo"]})
    r["years_listed"] = sorted(int(y) for y in r["labels"])
out = {"_readme": f"Per-card labels from the archived sparkcapital.com listings, years {sorted(set(years))}: WordPress /companies/ 2015-2017 (sector, geography and a seed/venture/growth class per card, per-company pages), the 2018-2019 WordPress redesign (sector sections, seed/venture/growth class, website links) and the 2020 B12 site (tag-sector-*, tag-stage-*; 'alumni' = exited). Generated by scratch/wp-listing-tags.py from the wayback-pull raw snapshots. The stage class describes the company as listed, not the entry round (COLLECTION.md §6): scored on the gate before it may corroborate.",
       "rows": list(rows.values())}
write_atomic(P.site / "wp-companies-2015-2020.json", json.dumps(out, indent=1) + "\n")
from collections import Counter
print(f"{len(rows)} companies over years {sorted(set(years))}; stage_site_first:", Counter(r["stage_site_first"] for r in rows.values()))
